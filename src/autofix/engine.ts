import * as core from "@actions/core";
import * as exec from "@actions/exec";
import * as io from "@actions/io";
import fs from "node:fs";
import path from "node:path";

import type { ExecutionTask } from "./types.js";

export interface ExecutionResult {
  task: ExecutionTask;
  exitCode: number;
  error?: Error;
}

/**
 * Resolves local project binary safely without falling back to `npx` (which could download unpinned packages).
 * On Unix-like systems, checks node_modules/.bin/<tool>.
 * On Windows, resolves executable shims (preferring .cmd, then .bat, .exe, or extensionless).
 * Falls back to PATH via io.which.
 */
export async function resolveProjectBinary(
  cwd: string,
  toolBinary: string,
  platform: NodeJS.Platform = process.platform,
): Promise<string | undefined> {
  const binDir = path.join(cwd, "node_modules", ".bin");

  const SUPPORTED_WIN_EXTENSIONS = new Set([".cmd", ".bat", ".exe"]);

  if (platform === "win32") {
    const ext = path.extname(toolBinary).toLowerCase();
    // If the binary already has an extension, only accept supported Windows extensions
    if (ext) {
      if (!SUPPORTED_WIN_EXTENSIONS.has(ext)) {
        return undefined;
      }
      const explicitPath = path.join(binDir, toolBinary);
      if (fs.existsSync(explicitPath)) {
        return explicitPath;
      }
    } else {
      // Shims generated by npm/pnpm on Windows include .cmd, .bat, and .exe.
      // @actions/exec launches .cmd and .bat through cmd.exe /D /S /C and .exe directly.
      // Extensionless executable resolution order on Windows:
      // 1. .cmd
      // 2. .bat
      // 3. .exe
      // 4. Extensionless executable
      const winExtensions = [".cmd", ".bat", ".exe", ""];
      for (const winExt of winExtensions) {
        const candidate = path.join(binDir, `${toolBinary}${winExt}`);
        if (fs.existsSync(candidate)) {
          return candidate;
        }
      }
    }
  } else {
    const localBinPath = path.join(binDir, toolBinary);
    if (fs.existsSync(localBinPath)) {
      return localBinPath;
    }
  }

  const pathBin = await io.which(toolBinary, false);
  if (pathBin) {
    if (platform === "win32") {
      const pathExt = path.extname(pathBin).toLowerCase();
      if (pathExt && !SUPPORTED_WIN_EXTENSIONS.has(pathExt)) {
        return undefined;
      }
    }
    return pathBin;
  }

  return undefined;
}

export class ExecutionEngine {
  constructor(private readonly platform: NodeJS.Platform = process.platform) {}

  /**
   * Resolves the executable path for a task at execution time (after dependencies are provisioned).
   */
  public async resolveTaskExecutable(task: ExecutionTask): Promise<string> {
    if (task.toolId === "npm-scripts") {
      return task.executable;
    }

    if (task.toolId === "ruff") {
      const hasRuff = Boolean(await io.which("ruff", false));
      if (!hasRuff) {
        throw new Error("Required Python binary 'ruff' is not available in PATH.");
      }
      return "ruff";
    }

    // Tool adapters: resolve from node_modules/.bin or PATH
    const resolved = await resolveProjectBinary(task.cwd, task.executable, this.platform);
    if (!resolved) {
      const toolName = task.toolName || task.toolId;
      const depName = task.requiredPackage || task.executable;
      throw new Error(
        `Configured tool "${toolName}" could not run: executable "${task.executable}" is not available in node_modules/.bin or PATH. Please install "${depName}" in project dependencies.`,
      );
    }
    return resolved;
  }

  /**
   * Executes tasks sequentially, capturing diagnostics and aggregating any task errors.
   */
  public async executeTasks(tasks: ExecutionTask[]): Promise<ExecutionResult[]> {
    const results: ExecutionResult[] = [];

    for (const task of tasks) {
      const displayCmd = `${task.executable} ${task.args.join(" ")}`.trim();

      try {
        const resolvedExecutable = await this.resolveTaskExecutable(task);
        core.info(`Executing: ${displayCmd}`);

        const env = task.env
          ? (Object.fromEntries(
              Object.entries({ ...process.env, ...task.env }).filter(
                (entry): entry is [string, string] => entry[1] !== undefined,
              ),
            ) as Record<string, string>)
          : undefined;

        const exitCode = await exec.exec(resolvedExecutable, task.args, {
          cwd: task.cwd,
          env,
          ignoreReturnCode: true,
        });

        if (exitCode !== 0) {
          const errMessage =
            task.toolId === "ruff"
              ? `Ruff command "${displayCmd}" failed. Check Python and Ruff configuration.`
              : task.toolId === "npm-scripts"
                ? `Script "${task.args[1] || displayCmd}" failed while executing "${displayCmd}".`
                : `Task "${task.id}" (${displayCmd}) failed with exit code ${exitCode}.`;
          results.push({
            task,
            exitCode,
            error: new Error(errMessage),
          });
        } else {
          results.push({ task, exitCode });
        }
      } catch (err) {
        const error = err instanceof Error ? err : new Error(String(err));
        results.push({
          task,
          exitCode: 1,
          error,
        });
      }
    }

    return results;
  }
}
