import * as io from "@actions/io";
import fs from "node:fs";
import path from "node:path";

const SUPPORTED_WIN_EXTENSIONS = new Set([".cmd", ".bat", ".exe"]);

export { SUPPORTED_WIN_EXTENSIONS };

/**
 * Validates that a file exists and is executable.
 * On Unix-like platforms, verifies file existence, regular file status, and executable permission via fs.accessSync(..., X_OK).
 * On Windows, verifies file existence and regular file status without applying Unix X_OK checks.
 */
export function isExecutableBinary(
  filePath: string,
  platform: NodeJS.Platform = process.platform,
): boolean {
  try {
    if (!fs.existsSync(filePath)) {
      return false;
    }
    const stat = fs.statSync(filePath);
    if (!stat.isFile()) {
      return false;
    }
    if (platform === "win32") {
      return true;
    }
    fs.accessSync(filePath, fs.constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

/**
 * Resolves the Node.js runtime executable.
 * Node.js is typically a system-level binary, so this primarily checks PATH via io.which.
 * On Windows, validates the extension is supported (.exe, .cmd, .bat).
 */
export async function getNodeExecutable(
  platform: NodeJS.Platform = process.platform,
): Promise<string | undefined> {
  try {
    const pathBin = await io.which("node", false);
    if (pathBin) {
      if (platform === "win32") {
        const pathExt = path.extname(pathBin).toLowerCase();
        if (pathExt && !SUPPORTED_WIN_EXTENSIONS.has(pathExt)) {
          return undefined;
        }
      }
      return pathBin;
    }
  } catch {
    return undefined;
  }
  return undefined;
}

/**
 * Resolves local project binary safely without falling back to `npx` (which could download unpinned packages).
 * On Unix-like systems, checks node_modules/.bin/<tool> with executable permission.
 * On Windows, resolves executable shims (preferring .cmd, then .bat, .exe, or extensionless).
 * Falls back to PATH via io.which.
 */
export async function resolveProjectBinary(
  cwd: string,
  toolBinary: string,
  platform: NodeJS.Platform = process.platform,
): Promise<string | undefined> {
  const binDir = path.join(cwd, "node_modules", ".bin");

  if (platform === "win32") {
    const ext = path.extname(toolBinary).toLowerCase();
    // If the binary already has an extension, only accept supported Windows extensions
    if (ext) {
      if (!SUPPORTED_WIN_EXTENSIONS.has(ext)) {
        return undefined;
      }
      const explicitPath = path.join(binDir, toolBinary);
      if (isExecutableBinary(explicitPath, platform)) {
        return explicitPath;
      }
    } else {
      // Shims generated by npm/pnpm on Windows include .cmd, .bat, and .exe.
      // @actions/exec launches .cmd and .bat through cmd.exe /D /S /C and .exe directly.
      // Extensionless executable resolution order on Windows:
      // 1. .cmd
      // 2. .bat
      // 3. .exe
      // 4. Extensionless executable
      const winExtensions = [".cmd", ".bat", ".exe", ""];
      for (const winExt of winExtensions) {
        const candidate = path.join(binDir, `${toolBinary}${winExt}`);
        if (isExecutableBinary(candidate, platform)) {
          return candidate;
        }
      }
    }
  } else {
    const localBinPath = path.join(binDir, toolBinary);
    if (isExecutableBinary(localBinPath, platform)) {
      return localBinPath;
    }
  }

  try {
    const pathBin = await io.which(toolBinary, false);
    if (pathBin) {
      if (platform === "win32") {
        const pathExt = path.extname(pathBin).toLowerCase();
        if (pathExt && !SUPPORTED_WIN_EXTENSIONS.has(pathExt)) {
          return undefined;
        }
      }
      return pathBin;
    }
  } catch {
    return undefined;
  }

  return undefined;
}
